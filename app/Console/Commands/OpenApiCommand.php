<?php

namespace App\Console\Commands;

use App\Http\Controllers\Api\ResourceController;
use App\Resources\Registry;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Route;

/** Generates OpenAPI 3.1 (docs/openapi.json) and TypeScript resource types (resources/js/api/generated.ts) from the registry and routes. */
class OpenApiCommand extends Command
{
    protected $signature = 'legacy:openapi {--check : Fail if generated files are out of date}';

    protected $description = 'Generate the OpenAPI document and TypeScript client types';

    private const JSON = ['s' => ['type' => 'string'], 't' => ['type' => 'string'], 'i' => ['type' => 'integer'], 'y' => ['type' => 'integer'],
        'm' => ['type' => 'string', 'pattern' => '^-?\\d+(\\.\\d+)?$', 'description' => 'Decimal string (money)'], 'q' => ['type' => 'string', 'description' => 'Decimal string (quantity)'],
        'p' => ['type' => 'string', 'description' => 'Decimal string (price)'], 'r' => ['type' => 'string', 'description' => 'Decimal string (rate)'],
        'f' => ['type' => 'string', 'description' => 'Decimal fraction 0..1'], 'pct' => ['type' => 'string', 'description' => 'Decimal string'],
        'd' => ['type' => 'string', 'format' => 'date'], 'dt' => ['type' => 'string', 'format' => 'date-time'], 'b' => ['type' => 'boolean'],
        'j' => ['type' => ['object', 'array']], 'cur' => ['type' => 'string', 'pattern' => '^[A-Z]{3}$'], 'ref' => ['type' => 'string', 'description' => 'ULID'],
        'poly' => ['type' => 'string', 'description' => 'ULID of the record named by the sibling *_type field']];

    private const TS = ['s' => 'string', 't' => 'string', 'i' => 'number', 'y' => 'number', 'm' => 'Decimal', 'q' => 'Decimal', 'p' => 'Decimal', 'r' => 'Decimal',
        'f' => 'Decimal', 'pct' => 'Decimal', 'd' => 'ISODate', 'dt' => 'string', 'b' => 'boolean', 'j' => 'unknown', 'cur' => 'string', 'ref' => 'Ulid', 'poly' => 'Ulid'];

    public function handle(): int
    {
        $schemas = [];
        $ts = "// Generated by `php artisan legacy:openapi` from App\\Resources\\Registry. Do not edit.\n\nexport type Ulid = string;\nexport type Decimal = string;\nexport type ISODate = string;\n\n";
        $names = [];
        foreach (Registry::all() as $type => $def) {
            $props = ['id' => ['type' => 'string'], 'scope_id' => ['type' => 'string'], 'edit_version' => ['type' => 'integer'], '_title' => ['type' => ['string', 'null']]];
            $required = [];
            $iface = 'export interface '.$this->pascal($type)." {\n  id: Ulid;\n  type: '{$type}';\n  scope_id?: Ulid;\n  edit_version: number;\n  _title: string | null;\n  _redacted?: string[];\n  created_at: string | null;\n  updated_at: string | null;\n";
            foreach ($def['fields'] as $name => $spec) {
                $f = Registry::field($spec);
                $schema = $f['type'] === 'enum' ? ['type' => 'string', 'enum' => $f['values']] : (self::JSON[$f['type']] ?? ['type' => 'string']);
                if ($f['readonly']) {
                    $schema['readOnly'] = true;
                }
                $props[$name] = $schema;
                if ($f['required']) {
                    $required[] = $name;
                }
                $tsType = $f['type'] === 'enum' ? implode(' | ', array_map(fn ($v) => "'{$v}'", $f['values'])) : (self::TS[$f['type']] ?? 'string');
                $iface .= "  {$name}".($f['required'] ? '' : '?').": {$tsType}".($f['required'] ? '' : ' | null').";\n";
            }
            $iface .= "}\n\n";
            $ts .= $iface;
            $names[$type] = $this->pascal($type);
            $schemas[$this->pascal($type)] = ['type' => 'object', 'properties' => $props, 'required' => $required, 'description' => $def['label'].' ('.$def['domain'].')'];
        }
        $ts .= "export interface ResourceTypes {\n".implode('', array_map(fn ($t, $n) => "  {$t}: {$n};\n", array_keys($names), $names))."}\n\nexport type ResourceType = keyof ResourceTypes;\n";

        $paths = [];
        foreach (Route::getRoutes() as $route) {
            $uri = '/'.ltrim($route->uri(), '/');
            if (! str_starts_with($uri, '/api/v1') || str_contains($uri, '{any}')) {
                continue;
            }
            foreach (array_diff($route->methods(), ['HEAD']) as $method) {
                $op = ['operationId' => strtolower($method).str_replace(['/', '{', '}', '-'], ['_', '', '', '_'], substr($uri, 7)), 'responses' => ['200' => ['description' => 'OK'],
                    '202' => ['description' => 'Accepted (job queued)'], '4XX' => ['$ref' => '#/components/responses/Error']]];
                if ($method !== 'GET') {
                    $op['parameters'][] = ['$ref' => '#/components/parameters/IdempotencyKey'];
                }
                if (in_array($method, ['PATCH', 'DELETE'], true)) {
                    $op['parameters'][] = ['$ref' => '#/components/parameters/IfMatch'];
                }
                preg_match_all('/\{(\w+)\}/', $uri, $m);
                foreach ($m[1] as $p) {
                    $op['parameters'][] = ['name' => $p, 'in' => 'path', 'required' => true, 'schema' => ['type' => 'string']];
                }
                $paths[$uri][strtolower($method)] = $op;
            }
        }
        ksort($paths);
        $doc = ['openapi' => '3.1.0', 'info' => ['title' => 'McNutt Legacy API', 'version' => '1.0.0',
            'description' => 'Session-authenticated JSON API. Money is serialized as decimal strings. Mutations require Idempotency-Key; updates require If-Match with edit_version. Heavy operations return 202 with a job.'],
            'servers' => [['url' => 'https://legacy.mcnutt.cloud']], 'paths' => $paths,
            'components' => ['schemas' => $schemas + ['Error' => ['type' => 'object', 'properties' => ['error' => ['type' => 'object', 'properties' => [
                'code' => ['type' => 'string'], 'message' => ['type' => 'string'], 'details' => ['type' => ['object', 'null']], 'correlation_id' => ['type' => 'string']]]]]],
                'responses' => ['Error' => ['description' => 'Structured error', 'content' => ['application/json' => ['schema' => ['$ref' => '#/components/schemas/Error']]]]],
                'parameters' => ['IdempotencyKey' => ['name' => 'Idempotency-Key', 'in' => 'header', 'required' => true, 'schema' => ['type' => 'string', 'minLength' => 8, 'maxLength' => 128]],
                    'IfMatch' => ['name' => 'If-Match', 'in' => 'header', 'required' => true, 'schema' => ['type' => 'string']]]],
            'x-resources' => ResourceController::meta()];
        $json = json_encode($doc, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n";
        $files = [base_path('docs/openapi.json') => $json, resource_path('js/api/generated.ts') => $ts];
        $stale = false;
        foreach ($files as $path => $content) {
            if ($this->option('check')) {
                $stale = $stale || ! is_file($path) || file_get_contents($path) !== $content;
                continue;
            }
            @mkdir(dirname($path), 0755, true);
            file_put_contents($path, $content);
            $this->line('Wrote '.str_replace(base_path().'/', '', $path));
        }
        if ($this->option('check') && $stale) {
            $this->error('Generated API files are out of date. Run php artisan legacy:openapi.');

            return self::FAILURE;
        }

        return self::SUCCESS;
    }

    private function pascal(string $s): string
    {
        return str_replace(' ', '', ucwords(str_replace('_', ' ', $s)));
    }
}
